/** Turns an eval run into RESULTS.md: a summary, then one table per job. */
import type { DeckGrade, MediatorGrade, ShoppingGrade } from './graders.js';

export type CaseResult = {
  id: string;
  title: string;
  pass: boolean;
  costUsd: number;
  ms: number;
} & (
  | { job: 'deck'; grade: DeckGrade }
  | { job: 'mediator'; grade: MediatorGrade }
  | { job: 'shopping'; grade: ShoppingGrade }
);

export interface EvalRun {
  model: string;
  ranAt: string;
  results: CaseResult[];
}

const usd = (n: number) => `$${n.toFixed(4)}`;
const secs = (ms: number) => `${(ms / 1000).toFixed(1)}s`;
const mark = (pass: boolean) => (pass ? '✅' : '❌');
const list = (items: string[]) => (items.length ? items.join('; ') : '–');

function table(head: string[], rows: string[][]): string {
  return [
    `| ${head.join(' | ')} |`,
    `| ${head.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');
}

export function renderResults(run: EvalRun): string {
  const { results } = run;
  const passed = results.filter((r) => r.pass).length;
  const cost = results.reduce((s, r) => s + r.costUsd, 0);
  const deck = results.flatMap((r) => (r.job === 'deck' ? [r] : []));
  const mediator = results.flatMap((r) => (r.job === 'mediator' ? [r] : []));
  const shopping = results.flatMap((r) => (r.job === 'shopping' ? [r] : []));
  const violations = deck.reduce((s, r) => s + r.grade.hardViolations.length, 0);

  return `# Eval results

Generated by \`npm run eval\` (see [run.ts](run.ts)). Graded by code, not by a model:
[graders.ts](graders.ts). Cases: [cases.ts](cases.ts).

**${passed}/${results.length} cases pass** · hard-rule violations: **${violations}** · total cost
**${usd(cost)}** · model \`${run.model}\` · ${run.ranAt.slice(0, 10)}

## Deck builder (scout → curator → writer)

Taste = cards in the top 10 that fit the group's tastes; "code" is the best a
pure soft-score ranking of the same pool gets. Pass: no hard-rule breaks, no invented
or repeated cards from earlier rounds, a full deck, clean blurbs, taste within 2 of code.

${table(
  [
    'Case',
    'Pass',
    'Hard-rule breaks',
    'Invented',
    'Taste (AI / code)',
    'Disliked in top 10',
    'Seen before',
    'Blurbs kept',
    'Blurb problems',
    'Cost',
    'Time',
  ],
  deck.map(({ title, pass, grade: g, costUsd, ms }) => [
    title,
    mark(pass),
    String(g.hardViolations.length),
    String(g.invented),
    `${g.tasteHits} / ${g.baselineTasteHits}`,
    String(g.dislikedInTop10),
    String(g.seenInDeck),
    `${g.blurbsKept}/${g.picks}`,
    list(g.blurbProblems),
    usd(costUsd),
    secs(ms),
  ]),
)}

## Mediator (no match → compromise)

Pass: the pick survives the code check (a card from the deck, at most one yum behind the
leader) and the reason never mentions diets or health, or repeats instructions.

${table(
  ['Case', 'Pass', 'Picked (yums / top)', 'Reason length', 'Problems', 'Cost', 'Time'],
  mediator.map(({ title, pass, grade: g, costUsd, ms }) => [
    title,
    mark(pass),
    `${g.pickedYums ?? '?'} / ${g.topYums}`,
    String(g.reasonLength),
    list(g.problems),
    usd(costUsd),
    secs(ms),
  ]),
)}

## Sous-chef (shopping list)

Pass: a list that covers every ingredient exactly once (checked by code on submit),
duplicates on one line, no quantities in names, at most one "at home" miss.

${table(
  [
    'Case',
    'Pass',
    'Lines / ingredients',
    'Not merged',
    '"At home" misses',
    'Problems',
    'Cost',
    'Time',
  ],
  shopping.map(({ title, pass, grade: g, costUsd, ms }) => [
    title,
    mark(pass),
    `${g.lines} / ${g.ingredients}`,
    list(g.unmerged),
    list(g.atHomeMisses),
    list([...g.quantityInName, ...g.problems]),
    usd(costUsd),
    secs(ms),
  ]),
)}
`;
}
