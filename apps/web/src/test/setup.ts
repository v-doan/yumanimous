import '@testing-library/jest-dom/vitest';
import { cleanup } from '@testing-library/react';
import { MotionGlobalConfig } from 'motion/react';
import { afterEach } from 'vitest';

// Make Motion animations complete instantly so button-driven swipes resolve
// synchronously in jsdom. Drag physics are verified by hand on a real phone.
MotionGlobalConfig.skipAnimations = true;

// jsdom has no matchMedia; Motion's useReducedMotion reads it.
if (!window.matchMedia) {
  window.matchMedia = (query: string) =>
    ({
      matches: false,
      media: query,
      onchange: null,
      addEventListener: () => {},
      removeEventListener: () => {},
      addListener: () => {},
      removeListener: () => {},
      dispatchEvent: () => false,
    }) as MediaQueryList;
}

afterEach(() => cleanup());
